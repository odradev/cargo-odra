/// Cargo odra main parser function.
pub fn make_action() {
    let Cargo::Odra(args) = Cargo::parse();
    let current_dir = env::current_dir()
        .unwrap_or_else(|_| Error::CouldNotDetermineCurrentDirectory.print_and_die());
    match args.subcommand {
        OdraSubcommand::Build(build) => {
            let project = Project::detect(current_dir);
            BuildAction::new(
                &project,
                build.contracts_names,
                build.skip_schema,
                build.jobs,
            )
            .build();
        }
        OdraSubcommand::Test(test) => {
            let project = Project::detect(current_dir);
            TestAction::new(
                &project,
                test.backend,
                test.args,
                test.skip_build,
                test.test,
                test.filter,
                test.jobs,
            )
            .test();
        }
        OdraSubcommand::Generate(generate) => {
            let project = Project::detect(current_dir);
            GenerateAction::new(
                &project,
                generate.contract_name,
                generate.module,
                generate.template,
                generate.source,
            )
            .generate_contract();
        }
        OdraSubcommand::New(init) => {
            InitAction::generate_project(init, current_dir, false);
        }
        OdraSubcommand::Init(init) => {
            InitAction::generate_project(init, current_dir, true);
        }
        OdraSubcommand::Clean(_) => {
            let project = Project::detect(current_dir);
            clean_action(&project);
        }
        OdraSubcommand::Completions { shell } => {
            shell.generate(&mut Cargo::command(), &mut std::io::stdout());
        }
        OdraSubcommand::Schema(schema) => {
            let project = Project::detect(current_dir);
            SchemaAction::new(&project, schema.contracts_names).build();
        }
        OdraSubcommand::ListTemplates(list) => {
            let cargo_toml = Project::find_odra_cargo_toml(current_dir.clone());
            let odra_location = match cargo_toml {
                None => OdraLocation::from_source(list.source),
                Some(cargo_toml_path) => match list.source {
                    None => OdraLocation::from_project(load_cargo_toml(&cargo_toml_path)),
                    Some(source) => OdraLocation::from_source(Some(source)),
                },
            };

            ListTemplatesAction::list(odra_location);
        }
        OdraSubcommand::Account(account) => {
            run_account(*account).unwrap_or_else(|error| error.print_and_die());
        }
        OdraSubcommand::GenerateClient(_generate_client) => {
            let mut project = Project::detect(current_dir);
            GenerateClientAction::new(&mut project)
                .generate()
                .unwrap_or_else(|err| {
                    err.print_and_die();
                });
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const HASH: &str = "a1b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8f90";

    fn public_key() -> String {
        use casper_types::{PublicKey, SecretKey};
        PublicKey::from(&SecretKey::ed25519_from_bytes([5u8; 32]).unwrap()).to_hex_string()
    }

    fn account(args: &[&str]) -> Result<AccountSubcommand, clap::Error> {
        let mut argv = vec!["cargo", "odra", "account"];
        argv.extend_from_slice(args);
        let Cargo::Odra(odra) = Cargo::try_parse_from(argv)?;
        match odra.subcommand {
            OdraSubcommand::Account(account) => Ok(account.subcommand),
            _ => unreachable!(),
        }
    }

    #[test]
    fn parses_the_account_commands() {
        match account(&["set-key", HASH, "--weight", "2", "--yes", "--gas", "2.5"]).unwrap() {
            AccountSubcommand::SetKey(cmd) => {
                assert!(matches!(cmd.key, KeyArg::AccountHash(_)));
                assert_eq!(cmd.weight, 2);
                assert!(cmd.change.yes);
                assert_eq!(cmd.change.gas, "2.5");
            }
            other => panic!("{other:?}"),
        }
        match account(&[
            "configure",
            "--set-key",
            &format!("{}:1", public_key()),
            "--set-key",
            &format!("account-hash-{HASH}:3"),
            "--remove-key",
            HASH,
            "-d",
            "2",
            "-k",
            "3",
            "--account",
            HASH,
        ])
        .unwrap()
        {
            AccountSubcommand::Configure(cmd) => {
                assert_eq!(cmd.set_keys.len(), 2);
                assert!(matches!(cmd.set_keys[0], (KeyArg::PublicKey(_), 1)));
                assert!(matches!(cmd.set_keys[1], (KeyArg::AccountHash(_), 3)));
                assert_eq!(cmd.remove_keys.len(), 1);
                assert_eq!((cmd.deployment, cmd.key_management), (Some(2), Some(3)));
                assert!(cmd.change.account.is_some());
                assert_eq!(cmd.change.gas, "2.5");
            }
            other => panic!("{other:?}"),
        }
        assert!(matches!(
            account(&["info"]).unwrap(),
            AccountSubcommand::Info(AccountInfoCommand { key: None, .. })
        ));
    }

    #[test]
    fn rejects_bad_keys_and_weights() {
        let error = account(&["remove-key", "abc"]).unwrap_err().to_string();
        assert!(error.contains("is not a key"), "{error}");
        assert!(account(&["set-key", HASH, "--weight", "256"]).is_err());
        let error = account(&["configure", "--set-key", HASH])
            .unwrap_err()
            .to_string();
        assert!(error.contains("<key>:<weight>"), "{error}");
    }
}
